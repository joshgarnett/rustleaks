#[test]
fn combines_validated_block_crcs() {
    let first = combine_crc(0, 0x8123_4567);
    assert_eq!(first, 0x8123_4567);
    assert_eq!(combine_crc(first, 0x89ab_cdef), 0x8bed_4720);
}

#[test]
fn accepts_zero_block_empty_stream() {
    assert_eq!(decode(EMPTY_STREAM, 8).unwrap(), Vec::<u8>::new());
}

#[test]
fn accepts_valid_single_block_stream() {
    let expected = b"rustleaks combined crc test\n";
    assert_eq!(decode(SINGLE_BLOCK_STREAM, 3).unwrap(), expected);
    assert_eq!(decode(SINGLE_BLOCK_STREAM, 1024).unwrap(), expected);
}

#[test]
fn accepts_valid_multi_block_stream_independent_of_output_chunks() {
    assert_eq!(count_magic(MULTI_BLOCK_STREAM, BLOCK_MAGIC), 3);
    let expected = expected_multi_block_output();
    assert_eq!(decode(MULTI_BLOCK_STREAM, 7).unwrap(), expected);
    assert_eq!(decode(MULTI_BLOCK_STREAM, 4096).unwrap(), expected);
}

#[test]
fn rejects_modified_final_combined_crc() {
    let mut corrupted = MULTI_BLOCK_STREAM.to_vec();
    let final_magic = find_magic(&corrupted, FINAL_MAGIC, true);
    assert_ne!((final_magic + 48) % 8, 0);
    flip_bit(&mut corrupted, final_magic + 48);

    let error = decode(&corrupted, 257).unwrap_err();
    assert_eq!(error.kind(), io::ErrorKind::Other);
    assert_eq!(error.to_string(), "combined stream crc mismatch");
}

#[test]
fn rejects_modified_block_crc_before_combining_it() {
    let mut corrupted = SINGLE_BLOCK_STREAM.to_vec();
    let block_magic = find_magic(&corrupted, BLOCK_MAGIC, false);
    flip_bit(&mut corrupted, block_magic + 48);

    let error = decode(&corrupted, 257).unwrap_err();
    assert_eq!(error.kind(), io::ErrorKind::Other);
    assert_eq!(error.to_string(), "bad crc");
}

#[test]
fn rejects_truncated_final_combined_crc() {
    let final_magic = find_magic(SINGLE_BLOCK_STREAM, FINAL_MAGIC, true);
    let combined_crc_start = final_magic + 48;
    let truncated_byte_len = (combined_crc_start + 31) / 8;
    let truncated = &SINGLE_BLOCK_STREAM[..truncated_byte_len];

    let error = decode(truncated, 257).unwrap_err();
    assert_eq!(error.kind(), io::ErrorKind::Other);
    assert_eq!(error.to_string(), "whole stream crc truncated");
}

fn decode(input: &[u8], buffer_size: usize) -> io::Result<Vec<u8>> {
    let mut reader = DecoderReader::new(input);
    let mut output = Vec::new();
    let mut buffer = vec![0; buffer_size];

    loop {
        let read = reader.read(&mut buffer)?;
        if read == 0 {
            return Ok(output);
        }
        output.extend_from_slice(&buffer[..read]);
    }
}

fn expected_multi_block_output() -> Vec<u8> {
    const PATTERN: &[u8] = b"abcdefghijklmnopqrstuvwxyz0123456789\n";
    (0..220_000)
        .map(|index| PATTERN[index % PATTERN.len()])
        .collect()
}

fn find_magic(input: &[u8], magic: u64, last: bool) -> usize {
    let mut positions = 32..=(input.len() * 8 - 48);
    if last {
        positions
            .rev()
            .find(|&position| read_bits(input, position, 48) == magic)
    } else {
        positions.find(|&position| read_bits(input, position, 48) == magic)
    }
    .expect("fixture must contain the requested magic")
}

fn count_magic(input: &[u8], magic: u64) -> usize {
    (32..=(input.len() * 8 - 48))
        .filter(|&position| read_bits(input, position, 48) == magic)
        .count()
}

fn read_bits(input: &[u8], start: usize, count: usize) -> u64 {
    (start..start + count).fold(0, |value, position| {
        let byte = input[position / 8];
        let bit = (byte >> (7 - position % 8)) & 1;
        (value << 1) | u64::from(bit)
    })
}

fn flip_bit(input: &mut [u8], position: usize) {
    input[position / 8] ^= 1 << (7 - position % 8);
}
